from django.core.management.base import BaseCommand
from django.utils import timezone
from datetime import datetime, timedelta, timezone as dt_timezone
import random
import math
from AppEnviroNode.models import SensorNode, SensorReading

class Command(BaseCommand):
    help = 'Generate historical sensor data for EnviroNode based on WAQI patterns'

    def add_arguments(self, parser):
        parser.add_argument(
            '--start-date',
            type=str,
            default='2026-04-01',
            help='Start date in YYYY-MM-DD format'
        )
        parser.add_argument(
            '--end-date',
            type=str,
            default='2026-05-31',
            help='End date in YYYY-MM-DD format'
        )
        parser.add_argument(
            '--node-mac',
            type=str,
            default='ENVIRONODE_001',
            help='MAC address of the sensor node'
        )

    def handle(self, *args, **options):
        start_date_str = options['start_date']
        end_date_str = options['end_date']
        node_mac = options['node_mac']

        start_date = datetime.fromisoformat(start_date_str).replace(tzinfo=dt_timezone.utc)
        end_date = datetime.fromisoformat(end_date_str).replace(tzinfo=dt_timezone.utc)

        # Get or create node
        node, created = SensorNode.objects.get_or_create(
            mac_address=node_mac,
            defaults={'name': 'EnviroNode Test Node'}
        )
        if created:
            self.stdout.write(f'Created node {node_mac}')

        # Delete existing readings in date range
        deleted_count = SensorReading.objects.filter(
            node=node,
            timestamp__gte=start_date,
            timestamp__lte=end_date
        ).delete()[0]
        self.stdout.write(f'Deleted {deleted_count} existing readings')

        # Parse WAQI data
        waqi_data = self.parse_waqi_data()

        # Generate readings
        readings = []
        current_time = start_date
        interval = timedelta(seconds=10)

        # For smoothing
        pm_buffer = []

        anomaly_count = 0

        while current_time <= end_date:
            # Get base AQI for this hour
            hour_key = current_time.replace(minute=0, second=0, microsecond=0)
            aqi = waqi_data.get(hour_key, 50)  # default to 50 if not found

            # Convert AQI to base PM2.5
            base_pm25 = self.aqi_to_pm25(aqi)

            # Add noise ±5-10
            noise = random.uniform(-8, 8)
            pm25_raw = base_pm25 + noise
            pm25_raw = max(2.1, pm25_raw)  # ensure >2

            # Apply moving average window 3
            pm_buffer.append(pm25_raw)
            if len(pm_buffer) > 3:
                pm_buffer.pop(0)
            pm25_smoothed = sum(pm_buffer) / len(pm_buffer)

            # Check for spikes >300 difference (but since values are low, unlikely)
            if len(pm_buffer) >= 2:
                prev_pm = pm_buffer[-2]
                if abs(pm25_smoothed - prev_pm) > 300:
                    pm25_smoothed = prev_pm  # reject spike

            # Check anomaly: sudden drop from >=30 to <=5
            if len(pm_buffer) >= 2 and prev_pm >= 30 and pm25_smoothed <= 5:
                anomaly_count += 1
                current_time += interval
                continue  # skip recording

            # Simulate sensor statuses
            pms_status = 'ok' if random.random() > 0.05 else 'error'  # 5% failure rate
            bme_status = 'ok' if random.random() > 0.05 else 'error'

            if pms_status == 'error' and bme_status == 'error':
                system_status = 'critical'
                pm1_0 = pm2_5 = pm10 = None
                temperature = humidity = pressure = gas_resistance = -1
            else:
                if pms_status == 'ok' and bme_status == 'ok':
                    system_status = 'normal'
                else:
                    system_status = 'degraded'

                if pms_status == 'ok':
                    pm2_5 = pm25_smoothed
                    pm1_0 = pm2_5 * random.uniform(0.5, 0.7)
                    pm10 = pm2_5 * random.uniform(1.2, 1.5)
                else:
                    pm1_0 = pm2_5 = pm10 = None

                if bme_status == 'ok':
                    # Smooth BME data - use persistent values with small changes
                    if not hasattr(self, 'bme_temp'):
                        self.bme_temp = random.uniform(25, 38)
                        self.bme_hum = random.uniform(40, 90)
                        self.bme_press = random.uniform(990, 1020)
                        self.bme_gas = random.uniform(5, 80)

                    self.bme_temp += random.uniform(-0.5, 0.5)
                    self.bme_temp = max(25, min(38, self.bme_temp))
                    self.bme_hum += random.uniform(-2, 2)
                    self.bme_hum = max(40, min(90, self.bme_hum))
                    self.bme_press += random.uniform(-1, 1)
                    self.bme_press = max(990, min(1020, self.bme_press))
                    self.bme_gas += random.uniform(-2, 2)
                    self.bme_gas = max(5, min(80, self.bme_gas))

                    temperature = self.bme_temp
                    humidity = self.bme_hum
                    pressure = self.bme_press
                    gas_resistance = self.bme_gas
                else:
                    temperature = humidity = pressure = gas_resistance = -1

            # Latency
            latency_ms = random.randint(100, 500) if random.random() > 0.1 else random.randint(800, 1500)

            reading = SensorReading(
                node=node,
                pm1_0=pm1_0,
                pm2_5=pm2_5,
                pm10=pm10,
                temperature=temperature,
                humidity=humidity,
                pressure=pressure,
                gas_resistance=gas_resistance,
                system_status=system_status,
                pms_status=pms_status,
                bme_status=bme_status,
                latency_ms=latency_ms,
                timestamp=current_time,
                is_anomaly=False  # we handled anomalies by skipping
            )
            # Calculate AQI
            if reading.pm2_5 is not None:
                from AppEnviroNode.utils import calculate_aqi
                reading.aqi, reading.aqi_level = calculate_aqi(reading.pm2_5)
            readings.append(reading)

            current_time += interval

            # Bulk insert every 1000 readings
            if len(readings) >= 1000:
                SensorReading.objects.bulk_create(readings)
                readings = []
                self.stdout.write(f'Inserted 1000 readings up to {current_time}')

        # Final bulk insert
        if readings:
            SensorReading.objects.bulk_create(readings)
            self.stdout.write(f'Inserted final {len(readings)} readings')

        self.stdout.write(f'Anomalies detected (not recorded): {anomaly_count}')
        self.stdout.write('Historical data generation complete')

    def aqi_to_pm25(self, aqi):
        """Convert AQI to PM2.5 concentration"""
        if aqi <= 50:
            return (aqi / 50.0) * 12.0
        elif aqi <= 100:
            return 12.0 + ((aqi - 50) / 50.0) * (35.4 - 12.0)
        elif aqi <= 150:
            return 35.4 + ((aqi - 100) / 50.0) * (55.4 - 35.4)
        elif aqi <= 200:
            return 55.4 + ((aqi - 150) / 50.0) * (150.4 - 55.4)
        elif aqi <= 300:
            return 150.4 + ((aqi - 200) / 100.0) * (250.4 - 150.4)
        else:
            return 250.4 + ((aqi - 300) / 200.0) * (500.4 - 250.4)

